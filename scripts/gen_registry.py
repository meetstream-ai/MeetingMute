#!/usr/bin/env python3
"""Builds MeetingMute's built-in app list from registry/apps.json.

Writes:
  Sources/MeetingMuteCore/Registry+Apps.swift   the list compiled into the app
  docs/SUPPORTED_APPS.md                        the full table with evidence
  README.md                                     the summary between the supported-apps markers

Usage:
  python3 scripts/gen_registry.py           regenerate
  python3 scripts/gen_registry.py --check   fail if anything is out of date (CI)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = os.path.join(ROOT, "registry", "apps.json")
SWIFT = os.path.join(ROOT, "Sources", "MeetingMuteCore", "Registry+Apps.swift")
DOC = os.path.join(ROOT, "docs", "SUPPORTED_APPS.md")
README = os.path.join(ROOT, "README.md")
START, END = "<!-- supported-apps:start -->", "<!-- supported-apps:end -->"

CATEGORIES = [
    ("notetaker", "Notetakers"),
    ("dictation", "Dictation and transcription"),
    ("recorder", "Recorders"),
    ("calendar", "Meeting reminders"),
    ("assistant", "AI assistants"),
]
CONFIDENCE = {"confirmed": "confirmed", "inferred": "inferred", "name-only": "nameOnly"}
PROMPT = {"window": "window", "banner": "banner", "fullscreen": "fullscreen",
          "auto-record": "autoRecord", "unknown": "unknown"}
PROMPT_TEXT = {"window": "Own popup window", "banner": "Notification banner", "fullscreen": "Full-screen reminder",
               "auto-record": "Records without asking", "unknown": "Not documented"}


def load():
    with open(REGISTRY, encoding="utf-8") as f:
        data = json.load(f)
    apps = data["apps"]
    errors, seen_ids, seen_names = [], {}, set()
    for app in apps:
        name = app["name"]
        if name in seen_names:
            errors.append(f"duplicate app name: {name}")
        seen_names.add(name)
        if app["category"] not in dict(CATEGORIES):
            errors.append(f"{name}: unknown category {app['category']}")
        if app["confidence"] not in CONFIDENCE:
            errors.append(f"{name}: unknown confidence {app['confidence']}")
        if app["prompt"] not in PROMPT:
            errors.append(f"{name}: unknown prompt {app['prompt']}")
        if not app.get("bundleIDs") and not app.get("appNames"):
            errors.append(f"{name}: needs bundleIDs or appNames")
        if app["confidence"] == "name-only" and app.get("bundleIDs"):
            errors.append(f"{name}: name-only apps must not list bundle IDs")
        if not app.get("evidence", "").startswith("http"):
            errors.append(f"{name}: needs an evidence link")
        for bid in app.get("bundleIDs", []):
            key = bid.lower()
            if key in seen_ids:
                errors.append(f"{name}: bundle ID {bid} is also listed under {seen_ids[key]}")
            seen_ids[key] = name
    if errors:
        sys.exit("registry/apps.json has problems:\n  " + "\n  ".join(errors))
    return data


def swift_str(s):
    return json.dumps(s, ensure_ascii=False)


def swift_list(items):
    return "[" + ", ".join(swift_str(i) for i in items) + "]"


def render_swift(data):
    lines = [
        "// Generated by scripts/gen_registry.py from registry/apps.json. Do not edit by hand.",
        "",
        "extension Registry {",
        f"    public static let version = {swift_str(data['version'])}",
        "",
        "    public static let apps: [KnownApp] = [",
    ]
    for a in data["apps"]:
        args = [f"name: {swift_str(a['name'])}", f"category: .{a['category']}"]
        for key in ("bundleIDs", "appNames", "excludeBundleIDs"):
            if a.get(key):
                args.append(f"{key}: {swift_list(a[key])}")
        args.append(f"confidence: .{CONFIDENCE[a['confidence']]}")
        args.append(f"prompt: .{PROMPT[a['prompt']]}")
        if a.get("fullScreen"):
            args.append("fullScreen: true")
        for key in ("keywords", "press", "neverPress"):
            if a.get(key):
                args.append(f"{key}: {swift_list(a[key])}")
        if a.get("offSwitch"):
            args.append(f"offSwitch: {swift_str(a['offSwitch'])}")
        args.append(f"evidence: {swift_str(a['evidence'])}")
        if a.get("status") == "discontinued":
            args.append("discontinued: true")
        if a.get("note"):
            args.append(f"note: {swift_str(a['note'])}")
        lines.append("        KnownApp(" + ", ".join(args) + "),")
    lines += [
        "    ]",
        "",
        "    public static let quietMicrophoneApps: [String] = [",
    ]
    ids = data["quietMicrophoneApps"]["bundleIDs"]
    for i in range(0, len(ids), 4):
        lines.append("        " + ", ".join(swift_str(x) for x in ids[i:i + 4]) + ",")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def md_escape(s):
    return s.replace("|", "\\|")


def render_doc(data):
    apps = data["apps"]
    out = [
        "# Supported apps",
        "",
        f"MeetingMute knows **{len(apps)} apps** that interrupt you when a call starts "
        f"(registry version {data['version']}). Any other app can be added by hand from the + button.",
        "",
        "Generated from [`registry/apps.json`](../registry/apps.json). To add or fix an app, edit that file and run "
        "`python3 scripts/gen_registry.py`. Every bundle ID needs a public source: a Homebrew cask, the Mac App Store, "
        "an MDM recipe, source code, or the app's own `Info.plist` (`mdls -name kMDItemCFBundleIdentifier /Applications/App.app`).",
        "",
        "**Match** says how MeetingMute recognises the app: *bundle ID* (confirmed by a primary source), "
        "*bundle ID (inferred)* (one secondary source), or *app name* (no public bundle ID yet, so only the exact app name is used).",
        "",
    ]
    for key, title in CATEGORIES:
        group = [a for a in apps if a["category"] == key]
        if not group:
            continue
        out += [f"## {title} ({len(group)})", "",
                "| App | Match | Prompt | Turn it off in the app | Source |",
                "|---|---|---|---|---|"]
        for a in sorted(group, key=lambda a: a["name"].lower()):
            if a.get("bundleIDs"):
                ids = "<br>".join(f"`{i}`" for i in a["bundleIDs"])
                match = ids + (" (inferred)" if a["confidence"] == "inferred" else "")
            else:
                match = "app name: " + ", ".join(f"*{n}*" for n in a["appNames"])
            name = md_escape(a["name"]) + (" (discontinued)" if a.get("status") == "discontinued" else "")
            off = md_escape(a.get("offSwitch") or "Not documented")
            out.append(f"| {name} | {match} | {PROMPT_TEXT[a['prompt']]} | {off} | [link]({a['evidence']}) |")
        out.append("")
    out += [
        "## Never touched",
        "",
        "Meeting apps and browsers are protected and never acted on: "
        "Zoom, Microsoft Teams, Slack, Webex, Discord, FaceTime, WhatsApp, Skype, GoTo Meeting, RingCentral, Amazon Chime, "
        "Telegram, Signal, Tuple, Around, Tencent Meeting, Element, Chrome, Arc, Dia, Safari, Edge, Brave, Firefox, Vivaldi, "
        "Opera, Chromium, Orion, Zen, Comet, ChatGPT Atlas and Sidekick.",
        "",
        f"MeetingMute also knows {len(data['quietMicrophoneApps']['bundleIDs'])} dictation apps, screen recorders and "
        "assistants that use the microphone but never prompt at call start (superwhisper, Willow, VoiceInk, Loom, "
        "CleanShot X…). It never suggests them as notetakers.",
        "",
    ]
    return "\n".join(out)


def render_readme_block(data):
    apps = [a for a in data["apps"] if a.get("status") != "discontinued"]
    lines = [START, ""]
    for key, title in CATEGORIES:
        names = sorted((a["name"] for a in apps if a["category"] == key), key=str.lower)
        if names:
            lines.append(f"**{title}:** " + ", ".join(names) + ".")
            lines.append("")
    lines += [f"See [all {len(data['apps'])} apps, their bundle IDs and where to turn each prompt off]"
              "(docs/SUPPORTED_APPS.md).", "", END]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    data = load()
    outputs = {SWIFT: render_swift(data), DOC: render_doc(data)}
    if os.path.exists(README):
        readme = open(README, encoding="utf-8").read()
        if START in readme and END in readme:
            head, rest = readme.split(START, 1)
            _, tail = rest.split(END, 1)
            text = head + render_readme_block(data) + tail
            n = len(data["apps"])
            text = re.sub(r"knows-\d+%20apps", f"knows-{n}%20apps", text)
            text = re.sub(r"Knows \d+ apps", f"Knows {n} apps", text)
            outputs[README] = text
    stale = []
    for path, text in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
    if check and stale:
        sys.exit("Out of date, run `python3 scripts/gen_registry.py`: " + ", ".join(stale))
    print(("Up to date" if not stale else "Updated " + ", ".join(stale)) + f" ({len(data['apps'])} apps)")


if __name__ == "__main__":
    main()
